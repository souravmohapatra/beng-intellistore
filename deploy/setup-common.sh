#!/usr/bin/env bash
# Shared safety checks for the two interactive setup entrypoints.

setup_die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

setup_preflight() {
  [[ ${EUID:-$(id -u)} -eq 0 ]] || setup_die 'Run this script with sudo.'
  [[ $(uname -s) == Linux ]] || setup_die 'Setup targets Linux with systemd.'
  [[ -t 0 ]] || setup_die 'Run interactively in a terminal; secrets and approvals are prompted.'
  command -v systemctl >/dev/null || setup_die 'systemd is required.'
  [[ -d /run/systemd/system ]] || setup_die 'systemd must be running.'
  umask 077
}

setup_dependencies() {
  local missing=() command_name
  for command_name in curl openssl python3; do
    command -v "$command_name" >/dev/null || missing+=("$command_name")
  done
  if ((${#missing[@]})); then
    command -v apt-get >/dev/null || setup_die "Install these prerequisites: ${missing[*]}"
    confirm "Install missing prerequisites (${missing[*]}) with apt?" || setup_die 'No packages installed.'
    apt-get update
    apt-get install -y "${missing[@]}"
  fi
  if ! command -v docker >/dev/null; then
    [[ -f /etc/os-release ]] || setup_die 'Cannot identify Docker package support.'
    # shellcheck disable=SC1091
    source /etc/os-release
    [[ ${ID:-} == ubuntu ]] || setup_die 'Install Docker Engine and Compose for this Linux distribution, then rerun.'
    confirm 'Install Ubuntu docker.io and docker-compose-v2, and enable Docker?' || setup_die 'Docker installation declined.'
    apt-get update
    apt-cache show docker.io docker-compose-v2 >/dev/null || setup_die 'Ubuntu Docker/Compose packages unavailable; install Docker then rerun.'
    apt-get install -y docker.io docker-compose-v2
    systemctl enable --now docker.service
  fi
}

setup_runtime_file() {
  local directory=$1
  [[ ! -L "$directory" ]] || setup_die "Refusing symlink config directory: $directory"
  install -d -m 0700 -o root -g root "$directory"
  ENV_FILE="$directory/runtime.env"
  [[ ! -L "$ENV_FILE" ]] || setup_die "Refusing symlink config file: $ENV_FILE"
  if [[ -e "$ENV_FILE" ]]; then
    [[ $(stat -c %u "$ENV_FILE") == 0 ]] || setup_die 'Existing runtime.env must be root-owned.'
    [[ $(stat -c %a "$ENV_FILE") == 600 ]] || setup_die 'Existing runtime.env must have mode 0600.'
  fi
}

setup_prompt() {
  local key=$1 label=$2 fallback=$3 current
  current=$(_existing "$key" || true)
  ask "$key" "$label [default: ${current:-$fallback}]"
  [[ -n ${!key} ]] || printf -v "$key" '%s' "$fallback"
}

setup_docker() {
  setup_prompt DOCKER_HOST 'Local Docker endpoint' 'unix:///var/run/docker.sock'
  [[ "$DOCKER_HOST" == unix:///* ]] || setup_die 'Only an explicit local Unix Docker endpoint is supported.'
  [[ -S ${DOCKER_HOST#unix://} ]] || setup_die "No Docker socket at ${DOCKER_HOST#unix://}; start the intended daemon before rerunning."
  export DOCKER_HOST
  docker --host="$DOCKER_HOST" info --format 'Docker root: {{.DockerRootDir}}'
  docker --host="$DOCKER_HOST" compose version
  write_env DOCKER_HOST "$DOCKER_HOST"
  local docker_root
  docker_root=$(docker --host="$DOCKER_HOST" info --format '{{.DockerRootDir}}')
  if [[ $docker_root == /var/snap/docker/* ]]; then
    warn 'Docker snap cannot use no-new-privileges=true (its documented AppArmor restriction).'
    warn 'Using false for this project only; non-root users, dropped capabilities and read-only app/worker filesystems remain.'
    write_env INTELLISTORE_NO_NEW_PRIVILEGES false
  else
    write_env INTELLISTORE_NO_NEW_PRIVILEGES true
  fi
}

setup_load_runtime() {
  # Files are generated by these scripts under a root-only directory. Never
  # evaluate values supplied over HTTP or copy a .env from an untrusted source.
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
}

setup_compose() (
  setup_load_runtime
  # Export root-only settings here, as systemd does. A snap-packaged Docker CLI
  # cannot necessarily read /etc/... itself; do not auto-load checkout .env files.
  docker --host="$DOCKER_HOST" compose --env-file /dev/null \
    --project-directory "$ROOT" -f "$COMPOSE_FILE" "$@"
)

setup_secret() {
  local key=$1 value
  value=$(_existing "$key" || true)
  if [[ -z "$value" ]]; then
    value=$(openssl rand -hex 32)
    write_env "$key" "$value"
  fi
}

setup_port() {
  if [[ ! $1 =~ ^[0-9]{1,5}$ ]] || ((10#$1 < 1024 || 10#$1 > 65535)); then
    setup_die 'Choose a TCP port from 1024 through 65535.'
  fi
}

setup_plain_path() {
  [[ $1 =~ ^/[A-Za-z0-9_./-]+$ ]] || setup_die 'Use an absolute deployment path containing only letters, digits, slash, dot, underscore, or hyphen (systemd mount prerequisites).'
}

setup_private_url() {
  python3 - "$1" <<'PY'
import ipaddress
import sys
from urllib.parse import urlsplit
p = urlsplit(sys.argv[1])
if p.scheme not in {'http', 'https'} or not p.hostname or p.username or p.password or p.query or p.fragment or p.path not in {'', '/'}:
    raise SystemExit('Use an http(s) origin without credentials, a path, query, or fragment.')
try:
    p.port
except ValueError:
    raise SystemExit('Invalid TCP port.')
try:
    address = ipaddress.ip_address(p.hostname)
except ValueError:
    # Private DNS is selected by the operator. Connectivity is checked separately.
    if any(c.isspace() for c in p.hostname):
        raise SystemExit('Invalid hostname.')
else:
    if not address.is_private and not address.is_loopback:
        raise SystemExit('Use a private LAN address or private DNS name.')
PY
}
